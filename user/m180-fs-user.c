/* M180: an ordinary, separately linked ring3 Linux ELF proves that its
 * openat/read/write/fsync/close syscalls reach the real IRQ-backed /async
 * ext4 partition. The host separately reads the physical raw disk after
 * QEMU exits; success here alone is never a persistence oracle. */
#define _GNU_SOURCE
#include <errno.h>
#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <time.h>
#include <unistd.h>

#define M180_SEED_SIZE 8192U
#define M180_OUTPUT_SIZE 12288U
#define M180_BLOCK_SIZE 4096U

static const char m180_seed_path[]="/async/host-seed.bin";
static const char m180_output_path[]="/async/guest-user.bin";
static const char m180_seed_header[]="M179_HOST_EXT4_SEED";
static const char m180_output_header[]="M180_USER_EXT4_SYSCALL";

static void require(int condition,const char *operation) {
    if(condition)return;
    fprintf(stderr,"[M180 USER FS FAIL] %s errno=%d\n",operation,errno);
    fflush(stderr);
    exit(180);
}

static uint8_t expected_byte(size_t at,int output) {
    const char *tag=output?m180_output_header:m180_seed_header;
    const size_t header_size=output?sizeof(m180_output_header):
                                      sizeof(m180_seed_header);
    if(at<header_size)return (uint8_t)tag[at];
    const size_t index=at-header_size;
    return (uint8_t)((index*(output?37U:31U)+
                      (output?97U:17U))&255U);
}

static void read_exact_compare(int fd,size_t length,int output) {
    uint8_t buffer[733]; /* Deliberately not filesystem-block aligned. */
    size_t offset=0;
    while(offset<length) {
        size_t take=sizeof(buffer);
        if(take>length-offset)take=length-offset;
        ssize_t got=read(fd,buffer,take);
        if(got<0 && errno==EINTR)continue;
        require(got>0 && (size_t)got<=take,"read real ext4 payload");
        for(size_t i=0;i<(size_t)got;i++)
            require(buffer[i]==expected_byte(offset+i,output),
                    "read data matches independently generated bytes");
        offset+=(size_t)got;
    }
    uint8_t end=0;
    require(read(fd,&end,1)==0,"exact ext4 EOF");
}

static int open_seed_when_ready(void) {
    /* Do not assume that scheduling a kernel filesystem worker also means
     * it has completed mounting the partition. A finite retry handles
     * either task/worker dispatch order without masking a missing broker. */
    /* Slow RV64/AArch64 system emulation may still be completing the
     * independent M179 journal flush when PID1 launches this process.
     * This is a bounded *mount admission* wait, not block-I/O polling. */
    for(unsigned attempt=0;attempt<1200U;attempt++) {
        int fd=openat(AT_FDCWD,m180_seed_path,O_RDONLY|O_CLOEXEC);
        if(fd>=0)return fd;
        if(errno!=ENOENT && errno!=EBUSY && errno!=EAGAIN)
            require(0,"open host-seeded physical /async ext4");
        if(attempt==1199U)break;
        struct timespec delay={.tv_sec=0,.tv_nsec=50000000L};
        while(nanosleep(&delay,&delay)<0 && errno==EINTR){}
    }
    require(0,"bounded wait for /async mount and user IRQ broker");
    return -1;
}

int main(void) {
    int fd=open_seed_when_ready();
    struct stat st={0};
    require(fstat(fd,&st)==0 && S_ISREG(st.st_mode) &&
            st.st_size==(off_t)M180_SEED_SIZE,
            "fstat genuine host-seeded ext4 inode");
    read_exact_compare(fd,M180_SEED_SIZE,0);
    require(close(fd)==0,"close host-seeded ext4 inode");

    fd=openat(AT_FDCWD,m180_output_path,
              O_WRONLY|O_CREAT|O_EXCL|O_CLOEXEC,0644);
    require(fd>=0,"openat O_CREAT|O_EXCL on physical ext4 partition");
    errno=0;
    int duplicate=openat(AT_FDCWD,m180_output_path,
                         O_WRONLY|O_CREAT|O_EXCL,0644);
    require(duplicate==-1 && errno==EEXIST,
            "exclusive creation checks actual ext4 inode");

    uint8_t block[M180_BLOCK_SIZE];
    for(size_t offset=0;offset<M180_OUTPUT_SIZE;offset+=sizeof(block)) {
        for(size_t i=0;i<sizeof(block);i++)
            block[i]=expected_byte(offset+i,1);
        size_t written=0;
        while(written<sizeof(block)) {
            ssize_t n=write(fd,block+written,sizeof(block)-written);
            if(n<0 && errno==EINTR)continue;
            require(n>0 && (size_t)n<=sizeof(block)-written,
                    "write actual 4096-byte ext4 data block");
            written+=(size_t)n;
        }
    }
    require(fstat(fd,&st)==0 && st.st_size==(off_t)M180_OUTPUT_SIZE,
            "written ext4 inode grew to 12KiB");
    require(fsync(fd)==0,"userspace fsync waits for physical device flush");
    require(close(fd)==0,"close user-written ext4 file after fsync");

    fd=openat(AT_FDCWD,m180_output_path,O_RDONLY|O_CLOEXEC);
    require(fd>=0,"reopen user-written physical ext4 file by pathname");
    require(fstat(fd,&st)==0 && S_ISREG(st.st_mode) &&
            st.st_size==(off_t)M180_OUTPUT_SIZE,
            "reopen fstat retains 12KiB persistent file length");
    read_exact_compare(fd,M180_OUTPUT_SIZE,1);
    require(close(fd)==0,"close reopened ext4 inode");
    require(stat(m180_output_path,&st)==0 && S_ISREG(st.st_mode) &&
            st.st_size==(off_t)M180_OUTPUT_SIZE,
            "stat physical ext4 pathname after all FDs closed");

    puts("[M180 USER FS SYSCALL PASS]");
    fflush(stdout);
    return 0;
}
