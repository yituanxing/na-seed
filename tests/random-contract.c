int main(void) {
    uint64_t key[4]={UINT64_C(0x0706050403020100),UINT64_C(0x0f0e0d0c0b0a0908),
                     UINT64_C(0x1716151413121110),UINT64_C(0x1f1e1d1c1b1a1918)};
    uint64_t zero[4]={0};
    uint8_t out[128];
    assert(!nas_random_bytes(out,1));
    assert(!nas_random_seed(zero,4));
    assert(!nas_random_seed(key,3));
    assert(nas_random_seed(key,4));
    assert(nas_random_bytes(out,1));
    assert(nas_random_bytes(out+1,63));
    assert(nas_random_bytes(out+64,64));
    assert(!memcmp(out,expected,sizeof(out)));
    assert(nas_random_seed(key,4));
    assert(nas_random_bytes(out,sizeof(out)));
    assert(!memcmp(out,expected,sizeof(out)));
    assert(!nas_random_seed(0,4));
    assert(!nas_random_bytes(out,1));
    assert(nas_random_getrandom(0,1,0)==(uint64_t)-ENOSYS);
    return 0;
}
