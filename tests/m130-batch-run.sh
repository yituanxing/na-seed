#!/bin/sh
# Fifteen globally new signed Alpine ELFs in seven independent software
# families. All failures are collected; no single failure aborts the batch.
PATH=/usr/sbin:/sbin:/usr/bin:/bin
HOME=/tmp
LC_ALL=C
LANG=C
export PATH HOME LC_ALL LANG
busy() { /bin/busybox "$@"; }

original_elf() {
    candidate=$1
    [ -x "$candidate" ] || return 1
    resolved=$(busy readlink -f "$candidate") || return 1
    case "$resolved" in /bin/busybox|/usr/bin/busybox) return 1 ;; esac
    magic=$(busy dd if="$resolved" bs=1 count=4 2>/dev/null |
            busy od -An -tx1 | busy tr -d ' \n')
    [ "$magic" = 7f454c46 ] || {
        echo "[M130 NOT AN ORIGINAL ELF] $candidate" >&2
        return 1
    }
    printf '%s\n' "$candidate"
}

seed_image() {
    # Four actual RGB pixels, used by independent BMP/GIF transformations.
    busy printf 'P3\n2 2\n255\n255 0 0\n0 255 0\n0 0 255\n255 255 0\n' \
        > "$1/pixels.ppm"
}
seed_archive() {
    busy printf 'M130_ARCHIVE_ALPHA\n' > "$1/alpha"
    busy printf 'M130_ARCHIVE_BETA\n' > "$1/beta"
    (cd "$1" && /usr/bin/zip -q seed.zip alpha beta)
}
seed_xattr() {
    busy printf 'M130_EXTENDED_ATTRIBUTE\n' > "$1/held"
}

run_case() {
    app=$1
    dir="/tmp/m130-$app"
    busy mkdir -p "$dir"
    case "$app" in
      ppmtobmp)
        exe=$(original_elf /usr/bin/ppmtobmp)
        seed_image "$dir"
        "$exe" "$dir/pixels.ppm" > "$dir/image.bmp" 2> "$dir/error"
        [ "$(busy head -c 2 "$dir/image.bmp")" = BM ] ;;
      bmptopnm)
        exe=$(original_elf /usr/bin/bmptopnm)
        seed_image "$dir"
        /usr/bin/ppmtobmp "$dir/pixels.ppm" > "$dir/image.bmp"
        "$exe" "$dir/image.bmp" > "$dir/roundtrip.ppm" 2> "$dir/error"
        busy head -c 2 "$dir/roundtrip.ppm" | busy grep -Eq '^P[36]$' ;;
      ppmtogif)
        exe=$(original_elf /usr/bin/ppmtogif)
        seed_image "$dir"
        "$exe" "$dir/pixels.ppm" > "$dir/image.gif" 2> "$dir/error"
        busy head -c 6 "$dir/image.gif" | busy grep -Eq '^GIF8[79]a$' ;;
      giftopnm)
        exe=$(original_elf /usr/bin/giftopnm)
        seed_image "$dir"
        /usr/bin/ppmtogif "$dir/pixels.ppm" > "$dir/image.gif"
        "$exe" "$dir/image.gif" > "$dir/roundtrip.ppm" 2> "$dir/error"
        busy head -c 2 "$dir/roundtrip.ppm" | busy grep -Eq '^P[36]$' ;;
      addr2line)
        exe=$(original_elf /usr/bin/addr2line)
        # Resolves a real address from the unchanged native BusyBox ELF.
        "$exe" -e /bin/busybox 0 > "$dir/line" 2> "$dir/error"
        busy grep -Eq '(:[0-9?]+|\?\?)' "$dir/line" ;;
      ranlib)
        exe=$(original_elf /usr/bin/ranlib)
        # Valid empty ar archive, generated by the guest without compiling.
        busy printf '!<arch>\n' > "$dir/empty.a"
        "$exe" "$dir/empty.a" > "$dir/report" 2> "$dir/error"
        [ -s "$dir/empty.a" ] ;;
      bsdcpio)
        exe=$(original_elf /usr/bin/bsdcpio)
        busy printf 'M130_ARCHIVE_CPIO\n' > "$dir/alpha"
        (cd "$dir" && busy printf 'alpha\n' | "$exe" -o -H newc \
            > archive.cpio 2> error)
        "$exe" -it < "$dir/archive.cpio" > "$dir/list" 2>> "$dir/error"
        busy grep -Fxq alpha "$dir/list" ;;
      bsdcat)
        exe=$(original_elf /usr/bin/bsdcat)
        busy printf 'M130_ARCHIVE_STREAM\n' > "$dir/plain"
        busy gzip -c "$dir/plain" > "$dir/plain.gz"
        "$exe" "$dir/plain.gz" > "$dir/restored" 2> "$dir/error"
        busy cmp -s "$dir/plain" "$dir/restored" ;;
      zipnote)
        exe=$(original_elf /usr/bin/zipnote)
        seed_archive "$dir"
        "$exe" "$dir/seed.zip" > "$dir/notes" 2> "$dir/error"
        busy grep -Fq '@ alpha' "$dir/notes"
        busy grep -Fq '@ beta' "$dir/notes" ;;
      zipsplit)
        exe=$(original_elf /usr/bin/zipsplit)
        seed_archive "$dir"
        (cd "$dir" && "$exe" -n 65536 seed.zip \
            > report 2> error)
        busy grep -Eq 'zip|Zip|ZIP' "$dir/report"
        # Upstream zipsplit chooses the split archive basename. Verify an
        # actual second ZIP was emitted, irrespective of that spelling.
        [ "$(busy find "$dir" -maxdepth 1 -name '*.zip' | busy wc -l)" -ge 2 ] ;;
      getfattr)
        exe=$(original_elf /usr/bin/getfattr)
        seed_xattr "$dir"
        /usr/bin/setfattr -n user.naseed -v M130_XATTR "$dir/held"
        "$exe" -n user.naseed --only-values "$dir/held" \
            > "$dir/value" 2> "$dir/error"
        busy grep -Fq M130_XATTR "$dir/value" ;;
      setfattr)
        exe=$(original_elf /usr/bin/setfattr)
        seed_xattr "$dir"
        "$exe" -n user.naseed -v M130_XATTR_NEW "$dir/held" \
            > "$dir/report" 2> "$dir/error"
        /usr/bin/getfattr -n user.naseed --only-values "$dir/held" \
            > "$dir/value"
        busy grep -Fq M130_XATTR_NEW "$dir/value" ;;
      getfacl)
        exe=$(original_elf /usr/bin/getfacl)
        seed_xattr "$dir"
        "$exe" -p "$dir/held" > "$dir/acl" 2> "$dir/error"
        busy grep -Fq 'user::' "$dir/acl"
        busy grep -Fq 'group::' "$dir/acl" ;;
      setfacl)
        exe=$(original_elf /usr/bin/setfacl)
        seed_xattr "$dir"
        "$exe" -m 'u::rw-,g::r--,o::---' "$dir/held" \
            > "$dir/report" 2> "$dir/error"
        /usr/bin/getfacl -p "$dir/held" > "$dir/acl"
        busy grep -Fq 'other::---' "$dir/acl" ;;
      filefrag)
        exe=$(original_elf /usr/sbin/filefrag)
        seed_xattr "$dir"
        "$exe" -v "$dir/held" > "$dir/extent" 2> "$dir/error"
        busy grep -Eq 'File size|extent|blocks' "$dir/extent" ;;
      *) echo "[M130 UNKNOWN CASE] $app" >&2; return 2 ;;
    esac
}

if [ "$#" -eq 2 ] && [ "$1" = --case ]; then
    set -eu
    if [ "${M130_TRACE:-0}" = 1 ]; then
        PS4='[M130 TRACE] '
        set -x
    fi
    run_case "$2"
    exit 0
fi
[ "$#" -eq 0 ] || exit 2
failed=0
for app in ppmtobmp bmptopnm ppmtogif giftopnm addr2line ranlib \
           bsdcpio bsdcat zipnote zipsplit getfattr setfattr \
           getfacl setfacl filefrag; do
    echo "[M130 CASE START] $app"
    case_log="/tmp/m130-$app-case.log"
    if M130_TRACE=1 /bin/sh /tests/m130-batch-run.sh --case "$app" > "$case_log" 2>&1; then
        upper=$(printf '%s' "$app" | busy tr '[:lower:]' '[:upper:]')
        printf 'M130_%s_PASS\n' "$upper"
    else
        rc=$?
        upper=$(printf '%s' "$app" | busy tr '[:lower:]' '[:upper:]')
        echo "[M130 $upper FAILED] original ELF rc=$rc" >&2
        busy tail -85 "$case_log" >&2 || :
        for detail in error report line list notes value acl extent image.bmp \
                      image.gif roundtrip.ppm archive.cpio; do
            if [ -s "/tmp/m130-$app/$detail" ]; then
                echo "[M130 FAILED OUTPUT $app/$detail]" >&2
                busy head -c 1200 "/tmp/m130-$app/$detail" >&2 || :
                echo >&2
            fi
        done
        printf 'M130_%s_FAIL\n' "$upper"
        failed=$((failed + 1))
    fi
done
if [ "$failed" -ne 0 ]; then
    echo "[M130 BATCH FAIL] $failed/15 original ELF programs, complete census" >&2
    echo M130_BATCH_FAIL
    exit 1
fi
echo M130_BATCH_PASS
