static struct nas_rv_trap_frame *live;
/* M194 only: correlate the *original* libcrypto .data.rel.ro bytes with
 * mmap and mprotect, to identify whether the two non-RELA data qwords are
 * already populated on file mapping or change during musl relocation.
 * This is a bounded read-only observation of the task's own mapped memory;
 * do not modify the original DSO, VMA policy or kernel syscall result. */
static void nas_rv_trace_libcrypto_relro(const char *stage,uint64_t nr,
                                         uint64_t range_start,
                                         uint64_t range_length) {
    static unsigned reports;
    if(reports>=12U || !range_length || !nas_current_task ||
       !nas_current_task->mm)return;
    struct nas_task *task=nas_current_task;
    const struct nas_anon_regions *regions=&task->mm->mmap_vmas;
    for(unsigned i=0;i<regions->capacity;i++) {
        const struct nas_anon_region *rx=&regions->slots[i];
        if(rx->kind!=NAS_VMA_FILE_PRIVATE_SNAPSHOT ||
           rx->file_offset!=0 || (rx->prot&5U)!=5U ||
           rx->end-rx->start!=UINT64_C(0x33f000))continue;
        if(rx->start>USER_LIMIT-UINT64_C(0x3a2420))continue;
        uint64_t q3=rx->start+UINT64_C(0x3a2418);
        if(range_start>q3 || range_length<=q3-range_start)continue;
        const struct nas_anon_region *rw=nas_vma_find(regions,q3);
        if(!rw || rw->kind!=NAS_VMA_FILE_PRIVATE_SNAPSHOT ||
           rw->file_offset>UINT64_C(0x3a2418) ||
           q3-rw->start!=UINT64_C(0x3a2418)-rw->file_offset)continue;
        uint64_t values[2]={0};
        int64_t n=nas_vm_read_task_bytes(task,q3,
                         (uint8_t *)(void *)values,sizeof(values));
        nas_print("[RV64 RELRO TRACE] stage=");nas_print(stage);
        nas_print(" nr=");nas_dec(nr);
        nas_print(" pid=");nas_dec(task->pid);
        nas_print(" q3_va=");nas_hex(q3);
        nas_print(" count=");nas_dec(n==16?2:0);
        nas_print(" q3=");nas_hex(values[0]);
        nas_print(" q4=");nas_hex(values[1]);
        nas_print(" region_prot=");nas_hex(rw->prot);
        nas_print(" range_start=");nas_hex(range_start);
        nas_print(" range_len=");nas_hex(range_length);
        nas_print("\n");
        reports++;
        return;
    }
}
/* Used by first user entry and by an execve that replaces a process image. */
uint64_t nas_rv_entry_stack_top;
uint64_t nas_rv_return_stack(const struct nas_rv_trap_frame *source) {
    const struct nas_task *task=nas_current_task;
    if (!nas_task_kernel_stack_ok(task))
        nas_fail("RV64 invalid task kernel stack at sret");
    uint64_t dest=task->kernel_stack_top-sizeof(*source);
    if (dest != (uint64_t)(uintptr_t)source)
        memcpy((void *)(uintptr_t)dest, source, sizeof(*source));
    return dest;
}

/* Architecture entry translates the full hardware register image to the
 * established 8-word Linux syscall contract used by the x86 kernel. */
void nas_rv_full_trap_c(struct nas_rv_trap_frame *frame) {
    uint64_t scause, stval;
    __asm__ volatile("csrr %0, scause" : "=r"(scause));
    __asm__ volatile("csrr %0, stval" : "=r"(stval));
    struct nas_exception exception=nas_exception_rv64(scause,frame->sstatus,
                                                       stval,frame->sepc);
    /* STIP is delegated by OpenSBI. It is a genuine asynchronous
     * user interrupt, not an ECALL: sepc points to the interrupted
     * instruction and MUST NOT be incremented. */
    if(scause == (UINT64_C(1)<<63 | 5U) && !(frame->sstatus & 0x100U)) {
        live=frame;
        nas_rv_timer_handle(frame);
        nas_signal_user_return((uint64_t *)(void *)frame);
        live=0;
        return;
    }
    /* SEIP arrives with the exact interrupted user SEPC, just like STIP.
     * Do not increment SEPC or treat it as a synchronous ECALL.  The PLIC
     * owns claim/complete and the generic IRQ core owns device callbacks. */
    if(scause == (UINT64_C(1)<<63 | 9U) && !(frame->sstatus & 0x100U)) {
        live=frame;
        nas_rv_plic_external_irq();
        nas_signal_user_return((uint64_t *)(void *)frame);
        live=0;
        return;
    }
    /* Real U-mode EBREAK/C.EBREAK generated by original GNU GDB after
     * PTRACE_POKETEXT. Hardware SEPC is the breakpoint's instruction PC:
     * do not increment it, and never mistake it for an ECALL. */
    if(scause==3U && !(frame->sstatus & 0x100U)) {
        struct nas_task *tracee=nas_current_task;
        live=frame;
        nas_arch_save_user_frame(tracee,0);
        nas_arch_save_fpu(tracee);
        /* The trap at the *actual decoded next PC* completes exactly
         * one user instruction. Restore old instruction before GDB can
         * read memory, and report TRAP_TRACE, not a normal BRKPT. */
        bool stepped=nas_ptrace_rv_step_hit(tracee,frame->sepc);
        bool traced=nas_ptrace_user_exception(tracee,NAS_SIGTRAP,stepped?2:1,
                                      frame->sepc,frame->x[2],frame->sepc);
        if(!traced)nas_sched_thread_group_exit(0,NAS_SIGTRAP);
        uint64_t resumed=nas_task_schedule((uint64_t *)(void *)frame);
        frame->x[10]=resumed;
        nas_signal_user_return((uint64_t *)(void *)frame);
        live=0;
        return;
    }
    if(exception.user &&
       nas_current_task && nas_current_task->state==NAS_TASK_RUNNING) {
        struct nas_exception_outcome outcome=
            nas_exception_dispatch(&exception,nas_current_task->mm);
        if(outcome.action==NAS_EXC_RETRY)return; /* retry unchanged SEPC */
        if(outcome.action==NAS_EXC_SIGNAL) {
            struct nas_task *tracee=nas_current_task;
            /* Preserve the first genuine, unresolved user page faults for
             * cross-ISA loader/runtime diagnosis. As on x86 [USERPF], the
             * faulting user PC, VA and native register image must be captured
             * before the fatal signal reaps the process. This observation
             * does not hide or recover a fault and is bounded on purpose. */
            if(exception.kind==NAS_EXC_MEMORY) {
                static unsigned user_fault_reports;
                if(user_fault_reports++<16U) {
                    nas_print("[RV64 USERPF] pid=");nas_dec(tracee->pid);
                    nas_print(" scause=");nas_hex(scause);
                    nas_print(" sepc=");nas_hex(frame->sepc);
                    nas_print(" stval=");nas_hex(stval);
                    nas_print(" sp=");nas_hex(frame->x[2]);
                    nas_print(" ra=");nas_hex(frame->x[1]);
                    nas_print(" tp=");nas_hex(frame->x[4]);
                    nas_print(" a0=");nas_hex(frame->x[10]);
                    nas_print(" a1=");nas_hex(frame->x[11]);
                    nas_print(" t0=");nas_hex(frame->x[5]);
                    nas_print(" t1=");nas_hex(frame->x[6]);
                    nas_print(" t2=");nas_hex(frame->x[7]);
                    nas_print(" a2=");nas_hex(frame->x[12]);
                    nas_print(" a3=");nas_hex(frame->x[13]);
                    nas_print(" a4=");nas_hex(frame->x[14]);
                    nas_print(" a5=");nas_hex(frame->x[15]);
                    nas_print(" a6=");nas_hex(frame->x[16]);
                    nas_print(" si_code=");nas_dec((uint64_t)outcome.si_code);
                    nas_print("\n");
                    /* A noncanonical SEPC often follows a corrupted
                     * indirect JALR in an mmaped DSO. Identify the call
                     * site and its load segment without trusting user VA
                     * as a kernel pointer or requiring debug symbols. */
                    if(frame->x[1]>=8 && frame->x[1]<USER_LIMIT-4) {
                        uint32_t words[3]={0};
                        int64_t count=nas_vm_read_task_bytes(tracee,
                            frame->x[1]-8,(uint8_t *)(void *)words,12);
                        nas_print("[RV64 CALLSITE] ra=");nas_hex(frame->x[1]);
                        nas_print(" code=");nas_hex(words[0]);
                        nas_print(" ");nas_hex(words[1]);
                        nas_print(" ");nas_hex(words[2]);
                        nas_print(" count=");nas_dec(count==12);
                        const struct nas_anon_region *v=nas_vma_find(
                            &tracee->mm->mmap_vmas,frame->x[1]-4);
                        if(v) {
                            nas_print(" map_start=");nas_hex(v->start);
                            nas_print(" map_end=");nas_hex(v->end);
                            nas_print(" file_offset=");nas_hex(v->file_offset);
                            nas_print(" prot=");nas_hex(v->prot);
                            nas_print(" kind=");nas_dec(v->kind);
                        }
                        nas_print("\n");
                    }
                    /* libcrypto.so.3 RV64 c.ld a5,32(a1) followed by
                     * c.bnez and c.jalr has exposed a noncanonical callback
                     * value. Read the actual data-table qwords in the
                     * faulted process, not a guessed host offset. The MM
                     * remote-copy helper validates every address. */
                    const uint64_t table_va=frame->x[11];
                    if(table_va<USER_LIMIT && UINT64_C(64)<=USER_LIMIT-table_va) {
                        uint64_t values[8]={0};
                        int64_t n=nas_vm_read_task_bytes(tracee,table_va,
                            (uint8_t *)(void *)values,sizeof(values));
                        nas_print("[RV64 CALLTARGET] a1=");nas_hex(table_va);
                        nas_print(" read_qwords=");nas_dec(n==64?8:0);
                        if(n==64)for(unsigned k=0;k<8;k++) {
                            nas_print(" q");nas_dec(k);
                            nas_print("=");nas_hex(values[k]);
                        }
                        const struct nas_anon_region *v=nas_vma_find(
                            &tracee->mm->mmap_vmas,table_va+32);
                        if(v) {
                            nas_print(" map_start=");nas_hex(v->start);
                            nas_print(" map_end=");nas_hex(v->end);
                            nas_print(" map_file_off=");nas_hex(v->file_offset);
                            nas_print(" callback_file_off=");
                            nas_hex(v->file_offset+table_va+32-v->start);
                            nas_print(" prot=");nas_hex(v->prot);
                            nas_print(" kind=");nas_dec(v->kind);
                        }
                        nas_print("\n");
                    }
                }
            }
            live=frame;
            nas_arch_save_user_frame(tracee,0);
            nas_arch_save_fpu(tracee);
            uint64_t signal_addr=exception.kind==NAS_EXC_ILLEGAL ?
                                 frame->sepc : stval;
            bool traced=nas_ptrace_user_exception(tracee,outcome.signo,
                         outcome.si_code,frame->sepc,frame->x[2],signal_addr);
            if(!traced)nas_sched_thread_group_exit(0,outcome.signo);
            uint64_t resumed=nas_task_schedule((uint64_t *)(void *)frame);
            frame->x[10]=resumed;
            nas_signal_user_return((uint64_t *)(void *)frame);
            live=0;
            return;
        }
    }
    if(scause != 8U || (frame->sstatus & 0x100U)) {
        nas_print("[RV64 FAULT] scause=");nas_hex(scause);
        nas_print(" sepc=");nas_hex(frame->sepc);
        nas_print(" stval=");nas_hex(stval);
        /* True invalid instruction diagnostic in the user VM. A
         * ptrace POKETEXT may have written a zero/invalid encoding;
         * distinguish target code clobber from missing ISA support. */
        if(scause==2U && nas_current_task) {
            uint32_t insn=0;
            int64_t bytes=nas_vm_read_task_bytes(nas_current_task,
                frame->sepc,(uint8_t *)(void *)&insn,4);
            nas_print(" insn=");nas_hex(insn);
            nas_print(" readable=");nas_dec(bytes==4);
        }
        nas_print(" tp=");nas_hex(frame->x[4]);
        nas_print(" sp=");nas_hex(frame->x[2]);
        nas_print("\n");
        nas_fail("unexpected RV64 user trap (not U-mode ECALL)");
    }
    frame->sepc += 4; /* ECALL is always an uncompressed 4-byte instruction. */
    uint64_t call[15]={frame->x[17],frame->x[10],frame->x[11],
        frame->x[12],frame->x[13],frame->x[14],frame->x[15],frame->sepc};
    const uint64_t trapped_nr=frame->x[17];
    const uint64_t trapped_start=frame->x[10];
    const uint64_t trapped_length=frame->x[11];
    struct nas_task *const trapped_task=nas_current_task;
    if(trapped_nr==226U)
        nas_rv_trace_libcrypto_relro("before-mprotect",trapped_nr,
                                    trapped_start,trapped_length);
    live=frame;
    uint64_t result=nas_ptrace_syscall_dispatch(call);
    if(nas_current_task==trapped_task &&
       (trapped_nr==222U || trapped_nr==226U))
        nas_rv_trace_libcrypto_relro(trapped_nr==222U?
                  "after-mmap":"after-mprotect",trapped_nr,
                  trapped_nr==222U?result:trapped_start,trapped_length);
    /* Scheduler may have replaced *frame* with another task's snapshot. */
    frame->x[10]=result;
    nas_signal_user_return((uint64_t *)(void *)frame);
    live=0;
}
void nas_arch_restore_cpu(const struct nas_task *task) {
    if (!nas_task_kernel_stack_ok(task)) nas_fail("RV64 switching to invalid stack");
    nas_rv_entry_stack_top = task->kernel_stack_top;
    nas_mmu_switch_root(nas_task_page_root(task));
    /* Never write to another suspended Task's live trap image. */
    nas_rv_restore_fp(task->arch.fp_regs);
}
uint64_t nas_arch_signal_user_sp(void) {
    if(!live)nas_fail("RV64 signal return outside live trap");
    return live->x[2];
}
void nas_arch_save_fpu(struct nas_task *task) {
    nas_rv_save_fp(task->arch.fp_regs);
}
void nas_arch_save_user_frame(struct nas_task *task,const uint64_t *frame) {
    (void)frame;
    if(!live) nas_fail("RV64 context capture outside syscall trap");
    for(unsigned i=0;i<32;i++) task->arch.user_regs[i]=live->x[i];
    task->arch.user_pc=live->sepc;
    task->arch.user_sp=live->x[2];
    task->arch.user_status=live->sstatus;
    task->arch.user_tls_base=live->x[4];
}
void nas_arch_set_saved_return(struct nas_task *task,uint64_t value) {
    task->arch.user_regs[10]=value; /* Linux RV64 a0 */
}
uint64_t nas_arch_saved_return(const struct nas_task *task) {
    return task->arch.user_regs[10];
}
void nas_arch_load_user_frame(const struct nas_task *task,uint64_t *frame) {
    (void)frame;
    if(!live) nas_fail("RV64 context restore outside syscall trap");
    for(unsigned i=0;i<32;i++) live->x[i]=task->arch.user_regs[i];
    live->sepc=task->arch.user_pc;
    live->sstatus=task->arch.user_status;
    live->x[4]=nas_task_tls_base(task);
}

/* Preserve trap identity across Task C continuation switches. */
void nas_arch_pin_live_trap(struct nas_task *t) {
    if(!t || !live)nas_fail("RV64 native park without trap");
    t->native_trap_frame=(uint64_t)(uintptr_t)live;
}
void nas_arch_bind_live_trap(const struct nas_task *t) {
    live=t && t->native_trap_frame ?
         (struct nas_rv_trap_frame *)(uintptr_t)t->native_trap_frame : 0;
    if(live)nas_arch_load_user_frame(t,0);
}
extern _Noreturn void nas_rv_user_resume_frame(struct nas_rv_trap_frame *);
_Noreturn void nas_arch_resume_saved_user(void) {
    struct nas_task *t=nas_current_task;
    if(!t || !nas_task_kernel_stack_ok(t))nas_fail("RV64 native resume invalid Task");
    struct nas_rv_trap_frame *f=(struct nas_rv_trap_frame *)(uintptr_t)
        (t->kernel_stack_top-sizeof(struct nas_rv_trap_frame));
    for(unsigned i=0;i<32;i++)f->x[i]=t->arch.user_regs[i];
    f->sepc=t->arch.user_pc;f->sstatus=t->arch.user_status;
    f->x[2]=t->arch.user_sp;f->x[4]=t->arch.user_tls_base;
    live=f;
    nas_signal_user_return((uint64_t *)(void *)f);
    t->kernel_exec.cpu.saved_sp=0;
    live=0;
    nas_rv_user_resume_frame(f);
}
